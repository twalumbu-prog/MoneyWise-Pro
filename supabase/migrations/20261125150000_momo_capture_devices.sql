-- One capture key per DEVICE instead of one per person, so any number of phones (two iPhones, iPhone + Android) can
-- send into the same account at once without switching each other off. Each captured / ignored / balance row also
-- remembers which device sent it.
create table if not exists public.momo_capture_devices (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null,
    organization_id uuid not null,
    device_id text not null,            -- generated by the app, kept on the phone; lets a re-connect replace its own key
    label text,                         -- "iPhone", "Android" … what the person sees
    platform text,                      -- ios | android | other
    token_hash text not null unique,
    created_at timestamptz not null default now(),
    last_seen_at timestamptz,
    revoked_at timestamptz,
    unique (user_id, device_id)
);
create index if not exists momo_capture_devices_user_idx on public.momo_capture_devices (user_id) where revoked_at is null;
alter table public.momo_capture_devices enable row level security;   -- API (service role) only, like the other capture tables

alter table public.momo_captures add column if not exists device_id uuid;
alter table public.momo_ignored_messages add column if not exists device_id uuid;
alter table public.momo_balance_checks add column if not exists device_id uuid;
